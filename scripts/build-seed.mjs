// Builds supabase/seed.sql from the JSON in supabase/seed/. Run: node scripts/build-seed.mjs
// The JSON files are the source of truth; edit them, then rebuild. The SQL is idempotent (ON CONFLICT DO NOTHING).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(readFileSync(join(root, "supabase/seed", f), "utf8"));

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const insert = (table, cols, rows, conflict = "do nothing") =>
  rows.length
    ? `insert into public.${table} (${cols.join(", ")}) values\n${rows.map((r) => `  (${cols.map((c) => q(r[c])).join(", ")})`).join(",\n")}\non conflict ${conflict};\n`
    : "";

const plans = read("plans.json").plans;
const people = read("people.json");
const ex = read("exercises.json").exercises;
const menu = read("menu.json");

const waiver = {
  en: [
    "I train at my own risk and will use the equipment safely.",
    "I have no medical condition that stops me exercising, or my doctor says it's OK.",
    "I'll follow the gym rules and the staff's directions.",
  ],
  th: [
    "ฉันออกกำลังกายโดยยอมรับความเสี่ยงเอง และจะใช้อุปกรณ์อย่างปลอดภัย",
    "ฉันไม่มีโรคประจำตัวที่ห้ามออกกำลังกาย หรือแพทย์อนุญาตแล้ว",
    "ฉันจะปฏิบัติตามกฎของยิมและคำแนะนำของพนักงาน",
  ],
  ru: [
    "Я тренируюсь на свой риск и безопасно пользуюсь оборудованием.",
    "У меня нет противопоказаний к нагрузкам, или врач разрешил тренировки.",
    "Я соблюдаю правила зала и указания персонала.",
  ],
};

let sql = `-- Generated by scripts/build-seed.mjs from supabase/seed/*.json. Do not edit by hand.\n-- Safe to run more than once.\n\n`;
sql += insert("plans", ["id", "name", "name_th", "kind", "audience", "price_thb", "duration_days", "duration_months", "sessions", "on_desk", "sort", "qashier_product", "qashier_modifier"], plans, "(id) do nothing");
sql += "\n" + insert("staff", ["name", "qashier_name"], people.staff, "(name) do nothing");
sql += "\n" + insert("coaches", ["slug", "name", "full_name", "email", "on_qr", "portal", "qashier_product", "photo_path"],
  people.coaches.map((c) => ({ ...c, photo_path: c.photo ?? null, portal: c.portal === "invited" ? "none" : c.portal })), "(slug) do nothing");
sql += "\n" + insert("exercises", ["slug", "name", "muscle_group", "muscle", "equipment", "log_type", "default_sets", "default_reps", "default_seconds", "default_minutes"], ex, "(slug) do nothing");
sql += "\n" + insert("menu_categories", ["id", "name_en", "name_th", "name_ru", "sort", "andy_group", "qashier_categories"], menu.categories, "(id) do nothing");
sql += "\n" + insert("menu_items", ["id", "category_id", "name_en", "name_th", "desc_en", "price_thb", "photo_path", "in_app", "qashier_products", "sort"],
  menu.items.map((i) => ({ ...i, photo_path: i.photo_key ? `menu/${i.photo_key}` : null })), "(id) do nothing");
sql += "\n" + insert("menu_option_groups", ["id", "label_en", "label_th", "category_ids", "sort", "qashier_group"], menu.option_groups, "(id) do nothing");
sql += "\n" + insert("menu_options", ["id", "group_id", "label_en", "label_th", "price_thb", "qashier_modifier", "sort"], menu.options, "(id) do nothing");
sql += "\n" + insert("waiver_versions", ["version", "texts"], [{ version: 1, texts: waiver }], "(version) do nothing");
sql += "\n" + insert("settings", ["key", "value"], [
  { key: "gym", value: { name: "Superfit", area: "Chalong, Phuket", timezone: "Asia/Bangkok", currency: "THB", vat_rate: 0.07, prices_include_vat: true } },
  { key: "rules", value: { expiring_soon_days: 7, renew_nudge_days: 3, duplicate_scan_seconds: 120, pt_undo_minutes: 10 } },
  { key: "languages", value: { members: ["en", "th", "ru"], staff: ["en", "th"] } },
], "(key) do nothing");

writeFileSync(join(root, "supabase/seed.sql"), sql);
console.log(`seed.sql: ${plans.length} plans, ${people.staff.length} staff, ${people.coaches.length} coaches, ${ex.length} exercises, ${menu.items.length} menu items, ${menu.options.length} options`);
